#!/usr/bin/env node
// Generates src/portal/portal-css.generated.mjs from the accepted Phase 1 stylesheet
// (src/portal/portal.css), so the portal Worker serves CSS from Worker code (no Workers
// Static Assets: Access identity is not propagated through the static-assets router).
// Usage: node scripts/build-assets.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { STAGING_ROOT, POC_ROOT } from './lib/paths.mjs';

const css = readFileSync(join(POC_ROOT, 'src/portal/portal.css'), 'utf8');
const sha = createHash('sha256').update(css).digest('hex');
const out = `// GENERATED by scripts/build-assets.mjs from commercial-poc/src/portal/portal.css. Do not edit.\n// source sha256: ${sha}\nexport const PORTAL_CSS_SHA256 = '${sha}';\nexport const PORTAL_CSS = ${JSON.stringify(css)};\n`;
const target = join(STAGING_ROOT, 'src/portal/portal-css.generated.mjs');
if (process.argv.includes('--check')) {
  const ok = existsSync(target) && readFileSync(target, 'utf8') === out;
  console.log(JSON.stringify({ check: ok ? 'ok' : 'stale', target: 'src/portal/portal-css.generated.mjs' }));
  process.exitCode = ok ? 0 : 1;
} else {
  writeFileSync(target, out);
  console.log(JSON.stringify({ written: 'src/portal/portal-css.generated.mjs', sha256: sha }));
}
