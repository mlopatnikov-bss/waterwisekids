#!/usr/bin/env node
// Builds a clean, real-pilot D1 seed: the approved pilot tenants (Northwest Philadelphia,
// Jersey Shore and, from the Manhattan expansion, Manhattan), their eleven approved
// locations and eight sponsored placements only. It deliberately creates no traffic,
// conversion, user or membership rows. Held locations (Andorra, Asbury Park, East
// Village) are never included. Manhattan has no ordinary-listing control campaign.
// The already-live D1 is extended with the Manhattan onboarding packet's d1-upsert.sql,
// never by re-seeding; onboarding tests prove both paths give the same rows.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MANIFEST_PATH, stateDir } from './lib/paths.mjs';
import { migratedD1 } from './lib/d1-sqlite.mjs';
import { loadManifestD1 } from './lib/seed-pipeline.mjs';
import { dumpSql } from './lib/sql-dump.mjs';
import { migrationFiles } from './lib/migrations.mjs';
import { tableSummary } from './build-seed.mjs';

export const PILOT_START = '2026-11-02';
export const PILOT_END = '2026-12-31';
export const PILOT_AT = '2026-11-02T05:00:00.000Z';
export const MANHATTAN_TENANT_ID = 'ten_52bf92991a0305d0';
// Manhattan: the seven venues verified in the 2026-11-02 official snapshot and WWK directory data.
export const MANHATTAN_LOCATION_IDS = Object.freeze([
  'loc_62b36f46fcdb5e47', // Upper East Side - Dwight School
  'loc_a0918a26c7b9cde7', // St. Bart's Church
  'loc_f512b73e99c5d550', // BMCC (Borough of Manhattan Community College)
  'loc_d73c8e16e071c820', // John Jay College
  'loc_0495184e2c71c89c', // Liberty Terrace
  'loc_0d1fa0c4a7ea58c8', // Wall Street
  'loc_f4f76e1ad2c26f8b', // The Continental
]);
export const PILOT_TENANT_IDS = Object.freeze(['ten_b234a48144f47f06', 'ten_9d294d23e0e9841e', MANHATTAN_TENANT_ID]);
const TENANTS = new Set(PILOT_TENANT_IDS);
const LOCATIONS = new Set(['loc_d3c46e7d6efc62f7', 'loc_3c6664af3a15b390', 'loc_b5b7d777c4bea81a', 'loc_096d7703f7c65cd6', ...MANHATTAN_LOCATION_IDS]);

export function pilotManifest(base) {
  const campaigns = base.campaigns.filter((x) => TENANTS.has(x.tenant_id) && x.kind === 'sponsored_pilot')
    .map((x) => ({ ...x, display_name: 'Sponsored pilot', starts_on: PILOT_START, ends_on: PILOT_END }));
  const campaignIds = new Set(campaigns.map((x) => x.campaign_id));
  const placements = base.placements.filter((x) => campaignIds.has(x.campaign_id) && x.kind === 'sponsored_card');
  const placementIds = new Set(placements.map((x) => x.placement_id));
  const schools = base.schools.filter((x) => TENANTS.has(x.tenant_id));
  const destinations = base.destinations.filter((x) => TENANTS.has(x.tenant_id) && (x.location_id === null || LOCATIONS.has(x.location_id)));
  const destinationIds = new Set(destinations.map((x) => x.destination_id));
  return {
    ...base,
    generated_at: PILOT_AT,
    generator: 'commercial-poc/staging/scripts/build-pilot-seed.mjs',
    fixture_notice: undefined,
    pilot_notice: 'Approved no-fee live pilot (Northwest Philadelphia, Jersey Shore, Manhattan); metrics begin 2026-11-02.',
    tenants: base.tenants.filter((x) => TENANTS.has(x.tenant_id)),
    schools,
    locations: base.locations.filter((x) => LOCATIONS.has(x.location_id)).map((x) => ({
      ...x,
      status_reason: 'Owner-approved for the live WWK commercial pilot beginning 2026-11-02.',
      verified_on: PILOT_START,
    })),
    users: [],
    memberships: [],
    campaigns,
    placements,
    placement_pages: base.placement_pages.filter((x) => placementIds.has(x.placement_id)),
    destinations,
    placement_destinations: base.placement_destinations.filter((x) => placementIds.has(x.placement_id) && destinationIds.has(x.destination_id)),
    conflicts: [],
    skipped_placements: [],
  };
}

export async function buildPilotSeedSql() {
  const manifest = pilotManifest(JSON.parse(readFileSync(MANIFEST_PATH, 'utf8')));
  const db = migratedD1(migrationFiles());
  await loadManifestD1(db, manifest, { at: PILOT_AT, actor: 'pilot-release' });
  const sql = await dumpSql(db, { header: [
    'WWK Commercial live-pilot seed. GENERATED by scripts/build-pilot-seed.mjs; do not edit.',
    `Approved locations only. Campaign ${PILOT_START}..${PILOT_END}.`,
    'No synthetic events, metrics, leads, enrollments or personal information.',
    'Administrator identity is provisioned separately as an opaque HMAC subject.',
  ] });
  const summary = { pilot_start: PILOT_START, pilot_end: PILOT_END, tables: await tableSummary(db), sql_sha256: createHash('sha256').update(sql).digest('hex'), sql_bytes: Buffer.byteLength(sql) };
  db.close();
  return { manifest, sql, summary };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = join(stateDir(), 'pilot');
  mkdirSync(out, { recursive: true });
  const { manifest, sql, summary } = await buildPilotSeedSql();
  writeFileSync(join(out, 'pilot-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(join(out, 'pilot-seed.sql'), sql);
  writeFileSync(join(out, 'pilot-seed.summary.json'), `${JSON.stringify(summary, null, 2)}\n`);
  console.log(JSON.stringify({ written: ['pilot-manifest.json', 'pilot-seed.sql', 'pilot-seed.summary.json'], summary }, null, 2));
}
