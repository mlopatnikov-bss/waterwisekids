#!/usr/bin/env node
// Builds the deterministic staging seed SQL by running the staging D1 code paths
// (scripts/lib/seed-pipeline.mjs) against an in-memory D1 adapter and dumping the result.
// Writes ONLY into the staging-local state directory (default staging/.data/seed/).
// Usage: node scripts/build-seed.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MANIFEST_PATH, stateDir } from './lib/paths.mjs';
import { migratedD1 } from './lib/d1-sqlite.mjs';
import { seedStaging, AS_OF, SYNTH } from './lib/seed-pipeline.mjs';
import { dumpSql, TABLES, rowsOf } from './lib/sql-dump.mjs';
import { migrationFiles } from './lib/migrations.mjs';

export async function tableSummary(db) {
  const tables = {};
  for (const [t, pk] of TABLES) {
    const { cols, rows } = await rowsOf(db, t, pk);
    const h = createHash('sha256');
    for (const r of rows) h.update(`${JSON.stringify(cols.map((c) => r[c]))}\n`);
    tables[t] = { rows: rows.length, sha256: h.digest('hex') };
  }
  return tables;
}

export async function buildSeedSql() {
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
  const db = migratedD1(migrationFiles());
  const r = await seedStaging(db, manifest, { asOf: AS_OF });
  const sql = await dumpSql(db, { header: [
    'WWK Commercial POC staging seed. GENERATED by scripts/build-seed.mjs; do not edit.',
    `Fixture: manifest ${manifest.manifest_version} generated ${manifest.generated_at}; synthetic seed ${SYNTH.seed}, ${SYNTH.from}..${SYNTH.to}; report time ${AS_OF}.`,
    'Synthetic data only. Users are inserted WITHOUT auth subjects; identities are provisioned separately.',
    'Idempotent: deletes every staging table (children first) and re-inserts (parents first).',
  ] });
  const summary = { as_of: AS_OF, synth: SYNTH, ingest: r.ingest, conversions: r.conv, tables: await tableSummary(db),
    sql_sha256: createHash('sha256').update(sql).digest('hex'), sql_bytes: Buffer.byteLength(sql) };
  db.close();
  return { sql, summary };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = join(stateDir(), 'seed');
  mkdirSync(out, { recursive: true });
  const { sql, summary } = await buildSeedSql();
  writeFileSync(join(out, 'staging-seed.sql'), sql);
  writeFileSync(join(out, 'staging-seed.summary.json'), `${JSON.stringify(summary, null, 2)}\n`);
  console.log(JSON.stringify({ written: [join(out, 'staging-seed.sql'), join(out, 'staging-seed.summary.json')], sql_bytes: summary.sql_bytes, sql_sha256: summary.sql_sha256, ingest: summary.ingest }, null, 2));
}
