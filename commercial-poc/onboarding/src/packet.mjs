// Place names are proper nouns: case-sensitive, whole words ("Brick", not "brick").
const placeRe = (n) => new RegExp(`(^|[^A-Za-z])${n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}($|[^A-Za-z])`, 'g');

/** Evidence-based sitemap / internal-link / content findings for each placement page. */
export function contentFindings(def, repo) {
  const sitemap = repo.read('sitemap.xml') || '';
  const targets = new Map(def.tenants.flatMap((t) => t.placements.map((p) => [p.page_path, p])));
  const markets = new Map(def.markets.map((m) => [m.market_key, m]));
  const inbound = new Map([...targets.keys()].map((k) => [k, new Set()]));
  const mentions = new Map([...targets.keys()].map((k) => [k, []]));
  const titles = new Map();
  for (const f of repo.listHtml()) {
    const html = repo.read(f); if (!html) continue;
    const title = /<title>([^<]*)<\/title>/i.exec(html)?.[1]?.trim();
    if (title) titles.set(title, [...(titles.get(title) || []), f]);
    const base = new URL(`/${f}`, SITE_ORIGIN);
    const linked = new Set();
    for (const m of html.matchAll(/href="([^"#?]+)[^"]*"/g)) {
      let u; try { u = new URL(m[1], base); } catch { continue; }
      if (u.origin === SITE_ORIGIN && targets.has(u.pathname) && u.pathname !== `/${f}`) { inbound.get(u.pathname).add(f); linked.add(u.pathname); }
    }
    let text = null;
    for (const [path, p] of targets) {
      if (linked.has(path) || path === `/${f}`) continue;
      text ??= editorialText(html);
      if (markets.get(p.market_key).place_names.some((n) => placeRe(n).test(text))) mentions.get(path).push(f);
    }
  }
  return [...targets.values()].map((p) => {
    const file = sourceFileFor(p.page_path).file; const html = repo.read(file);
    const canonicalUrl = `${SITE_ORIGIN}${p.page_path}`;
    const title = /<title>([^<]*)<\/title>/i.exec(html)?.[1]?.trim() ?? null;
    const body = editorialText(html);
    const names = markets.get(p.market_key).place_names;
    const ib = [...inbound.get(p.page_path)].sort();
    // Twin pages: the same town page in the other URL pattern (/swim-lessons/x.html <-> /swim-lessons-x.html).
    const base = file.split('/').pop();
    const twinFiles = (file.startsWith('swim-lessons/') ? [`swim-lessons-${base}`] : base.startsWith('swim-lessons-') ? [`swim-lessons/${base.slice('swim-lessons-'.length)}`] : [])
      .filter((x) => repo.read(x) !== null);
    const twins = twinFiles.map((x) => {
      const h = repo.read(x); const url = `${SITE_ORIGIN}/${x}`;
      const can = /<link[^>]*rel="canonical"[^>]*>/i.exec(h)?.[0]?.match(/href="([^"]+)"/)?.[1] ?? null;
      return { file: x, canonical: can, self_canonical: can === url, in_sitemap: sitemap.includes(`<loc>${url}</loc>`), title: /<title>([^<]*)<\/title>/i.exec(h)?.[1]?.trim() ?? null, editorial_words: wordCount(editorialText(h)) };
    });
    return {
      twin_pages: twins,
      page_path: p.page_path, source_file: file, market_key: p.market_key, title,
      duplicate_title_files: (titles.get(title) || []).filter((x) => x !== file).sort(),
      h1: /<h1[^>]*>([\s\S]*?)<\/h1>/i.exec(html)?.[1]?.replace(/<[^>]+>/g, '').trim() ?? null,
      canonical_ok: html.includes(`rel="canonical" href="${canonicalUrl}"`) || html.includes(`href="${canonicalUrl}" rel="canonical"`),
      in_sitemap: sitemap.includes(`<loc>${canonicalUrl}</loc>`),
      noindex: /<meta[^>]+name="robots"[^>]+noindex/i.test(html),
      editorial_words: wordCount(body),
      place_name_mentions: Object.fromEntries(names.map((n) => [n, (body.match(placeRe(n)) || []).length])),
      inbound_link_count: ib.length, inbound_link_files: ib,
      unlinked_mention_candidates: mentions.get(p.page_path).sort().slice(0, 10),
    };
  });
}

function worklistMd(def, findings) {
  const L = [`# Content worklist — ${def.definition_key}`, '', 'Generated from repository files only (no network). Every item is a proposal for human editorial review; this tool edits no city page, sitemap or link.', '',
    '| Page | Words | In sitemap | Canonical | Inbound links | Duplicate title |', '|---|---:|:-:|:-:|---:|:-:|'];
  for (const f of findings) L.push(`| \`${f.page_path}\` | ${f.editorial_words} | ${f.in_sitemap ? 'yes' : '**no**'} | ${f.canonical_ok ? 'ok' : '**check**'} | ${f.inbound_link_count} | ${f.duplicate_title_files.length ? '**yes**' : 'no'} |`);
  L.push('');
  for (const f of findings) {
    const items = [];
    if (!f.in_sitemap) items.push('Add the canonical URL to `sitemap.xml` (gated: editorial).');
    if (!f.canonical_ok) items.push('Canonical tag does not match the page URL; fix before tracking (gated: editorial).');
    if (f.noindex) items.push('Page is `noindex`; a sponsored card here earns no search traffic. Reconsider the placement.');
    if (f.duplicate_title_files.length) items.push(`Title duplicated by ${f.duplicate_title_files.map((x) => `\`${x}\``).join(', ')}.`);
    for (const t of f.twin_pages.filter((x) => x.self_canonical && x.in_sitemap)) items.push(`Overlapping page \`${t.file}\` ("${t.title}", ${t.editorial_words} words) is also self-canonical and in the sitemap. Decide which URL is primary before adding links or copy (gated: editorial; no automatic redirect or canonical change).`);
    if (f.inbound_link_count < 3) items.push(`Only ${f.inbound_link_count} internal links point here. Candidate linking pages that mention the area but do not link: ${f.unlinked_mention_candidates.length ? f.unlinked_mention_candidates.map((x) => `\`${x}\``).join(', ') : 'none found'}.`);
    L.push(`## \`${f.page_path}\``, '', ...(items.length ? items.map((x) => `- ${x}`) : ['- No structural gaps found.']), '');
  }
  return L.join('\n');
}

function rollbackMd(def, plans, deactivateOn) {
  const L = [`# Rollback / deactivation — ${def.definition_key}`, '', 'Order matters: stop public display first, then stop counting, then (optionally) remove access. Nothing is deleted from D1.', '',
    '1. **Remove cards from pages** (human-approved publish): apply each `rollback/remove-<slot>.diff` with `git apply`, preview, publish.',
    ...plans.map((p) => `   - \`${p.page_path}\` — \`${p.removal_patch}\``),
    `2. **Stop counting:** ${deactivateOn ? `apply \`deactivate.sql\` (sets campaign ends_on = ${deactivateOn}; the collector then rejects events as outside_campaign_window).` : 'regenerate this packet with `--deactivate-on YYYY-MM-DD` to get `deactivate.sql` (sets campaign ends_on so the collector rejects later events).'}`,
    '3. **Portal:** keep sponsor access for final reporting, or revoke per `portal-access-checklist.md`.',
    '4. **Restore:** re-apply `d1-upsert.sql` (restores ends_on from the definition) and re-apply `patches/*.diff` or re-run the packet.',
    '5. **Verify:** pages render without the card; official links still navigate; portal shows no events after the end date; record the incident or change in evidence.', ''];
  return L.join('\n');
}

function deactivateSql(def, on) {
  const L = [`-- WWK sponsor DEACTIVATION. GENERATED by ${GENERATOR}. Human approval gate: activation.`, `-- Ends campaigns on ${on}. Re-apply d1-upsert.sql to restore. No rows are deleted.`];
  for (const t of def.tenants) L.push(`UPDATE campaigns SET ends_on = ${q(on)} WHERE campaign_id = ${q(t.campaign.campaign_id)} AND tenant_id = ${q(t.tenant_id)} AND ends_on > ${q(on)};`);
  const detail = JSON.stringify({ definition_key: def.definition_key, ends_on: on });
  L.push(`INSERT INTO audit_log (at, actor, action, tenant_id, detail_json) SELECT ${q(`${on}T00:00:00.000Z`)}, ${q(ACTOR)}, 'sponsor.definition.deactivate', NULL, ${q(detail)}\n  WHERE NOT EXISTS (SELECT 1 FROM audit_log WHERE action = 'sponsor.definition.deactivate' AND detail_json = ${q(detail)});`, '');
  return L.join('\n');
}

/**
 * @returns { ok, errors, warnings, files: Record<path,string>, summary }
 */
export function buildPacket(def, ctx, { deactivateOn = null } = {}) {
  const v = validateDefinition(def, ctx);
  if (!v.ok) return { ok: false, errors: v.errors, warnings: v.warnings, files: {}, summary: null };
  if (deactivateOn !== null && !/^\d{4}-\d{2}-\d{2}$/.test(deactivateOn)) return { ok: false, errors: [{ code: 'invalid_value', path: '--deactivate-on', detail: 'YYYY-MM-DD' }], warnings: v.warnings, files: {}, summary: null };
  const defSha = definitionSha(def);
  const files = {}; const errors = []; const plans = []; const destinations = [];
  for (const t of def.tenants) for (const p of t.placements) {
    const r = planPlacement(def, t, p, ctx.repo);
    if (r.error) { errors.push(r.error); continue; }
    plans.push(r.plan);
    files[`cards/${p.slot_key}.html`] = `${r.card.join('\n')}\n`;
    if (r.diff) files[r.plan.patch] = r.diff;
    files[r.plan.removal_patch] = r.removalDiff;
    destinations.push({ tenant_id: t.tenant_id, campaign_id: t.campaign.campaign_id, placement_id: p.placement_id, slot_key: p.slot_key, page_path: p.page_path,
      destinations: placementDestinations(t, p).map((d) => ({ destination_id: d.destination_id, kind: d.kind, location_id: d.location_id, official_url: d.official_url, host: d.host, tagged_url: d.tagged_url, utm: d.utm })) });
  }
  if (errors.length) return { ok: false, errors, warnings: v.warnings, files: {}, summary: null };
  const ids = expectedIds(def).map((x) => ({ prefix: x.prefix, id: x.expected, natural_key: x.natural_key, path: x.path, declared: x.given !== null }));
  const findings = contentFindings(def, ctx.repo);
  files['ids.json'] = json(ids);
  files['patch-plan.json'] = json(plans);
  files['destinations.json'] = json(destinations);
  files['d1-upsert.sql'] = upsertSql(def, defSha);
  files['d1-preflight.sql'] = preflightSql(def);
  files['portal-memberships.sql'] = portalSql(def);
  files['portal-access-checklist.md'] = portalChecklist(def);
  files['content-worklist.json'] = json(findings);
  files['content-worklist.md'] = worklistMd(def, findings);
  files['rollback.md'] = rollbackMd(def, plans, deactivateOn);
  if (deactivateOn) files['deactivate.sql'] = deactivateSql(def, deactivateOn);

  const fileHashes = Object.fromEntries(Object.keys(files).sort().map((k) => [k, sha(files[k])]));
  const approvals = APPROVAL_GATES.map((g) => ({ gate: g, status: gateStatus(def, g) }));
  const pending = approvals.filter((a) => a.status !== 'recorded').map((a) => a.gate);
  const actions = plans.reduce((m, p) => ({ ...m, [p.action]: (m[p.action] || 0) + 1 }), {});
  const summary = {
    schema: 'wwk.sponsor-activation-packet', packet_version: 1, generator: GENERATOR,
    definition_key: def.definition_key, definition_sha256: defSha, prepared_on: def.prepared_on,
    mode: 'offline', network_actions: 0, deploy_actions: 0, database_actions: 0,
    counts: { tenants: def.tenants.length, locations: def.tenants.reduce((n, t) => n + t.locations.length, 0), destinations: def.tenants.reduce((n, t) => n + t.destinations.length, 0),
      campaigns: def.tenants.length, placements: plans.length, portal_users: def.portal.users.length, ids: ids.length },
    patch_actions: actions,
    approvals, pending_gates: pending, activation_ready: pending.length === 0,
    content_flags: findings.filter((f) => !f.in_sitemap || !f.canonical_ok || f.noindex || f.inbound_link_count < 3 || f.duplicate_title_files.length || f.twin_pages.some((x) => x.self_canonical && x.in_sitemap)).map((f) => f.page_path),
    warnings: v.warnings, files: fileHashes,
    packet_sha256: sha(Object.entries(fileHashes).map(([k, h]) => `${k} ${h}`).join('\n')),
  };
  files['summary.json'] = json(summary);
  return { ok: true, errors: [], warnings: v.warnings, files, summary };
}
