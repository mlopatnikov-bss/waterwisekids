export const GENERATOR = 'commercial-poc/onboarding (packet v1)';
export const ACTOR = 'sponsor-onboarding';
const sha = (s) => createHash('sha256').update(s).digest('hex');
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => `${JSON.stringify(v, null, 2)}\n`;
// Stable key order so JSON text (and hashes) never depend on object construction order.
export const canonical = (v) => (Array.isArray(v) ? v.map(canonical) : v && typeof v === 'object' ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, canonical(v[k])])) : v);
export const definitionSha = (def) => sha(JSON.stringify(canonical(def)));

const gateStatus = (def, gate) => def.approvals.find((a) => a.gate === gate)?.status ?? 'pending';

/** Per-placement patch plan against the current repo file. */
function planPlacement(def, tenant, p, repo) {
  const file = sourceFileFor(p.page_path).file;
  const text = repo.read(file);
  const lines = text.split('\n');
  const card = renderCardLines(def, tenant, p);
  const block = findCardBlock(lines, p.placement_id);
  let action; let diff = null; let activated = text; let start;
  if (block) {
    if (block.end < 0) return { error: { code: 'malformed_card_block', path: p.page_path, detail: 'card marker without closing script line' } };
    start = block.start;
    const live = lines.slice(block.start, block.end);
    if (live.join('\n') === card.join('\n')) action = 'unchanged';
    else { action = 'replace'; ({ diff, proposed: activated } = createEditDiff(file, text, [{ start, deleteCount: block.end - block.start, lines: card }])); }
  } else {
    const at = lines.findIndex((l) => l.trim() === p.anchor.text);
    start = at + 1; action = 'insert';
    ({ diff, proposed: activated } = createEditDiff(file, text, [{ start, deleteCount: 0, lines: card }]));
  }
  const removal = createEditDiff(file, activated, [{ start, deleteCount: card.length, lines: [] }]);
  return {
    plan: { slot_key: p.slot_key, placement_id: p.placement_id, page_path: p.page_path, source_file: file, action,
      card_lines: card.length, card_sha256: sha(`${card.join('\n')}\n`), file_sha256_before: sha(text), file_sha256_after: sha(activated),
      patch: diff ? `patches/${p.slot_key}.diff` : null, removal_patch: `rollback/remove-${p.slot_key}.diff` },
    card, diff, removalDiff: removal.diff,
  };
}

function upsertSql(def, defSha) {
  const ready = gateStatus(def, 'sponsor_terms') === 'recorded' && gateStatus(def, 'source_verification') === 'recorded';
  const L = [
    `-- WWK sponsor activation upsert. GENERATED by ${GENERATOR}; do not edit.`,
    `-- Definition ${def.definition_key} sha256 ${defSha}.`,
    '-- Idempotent: every row is INSERT ... ON CONFLICT DO UPDATE (or DO NOTHING). No DELETE, no DROP.',
    '-- Ownership guard: an existing row owned by another tenant is never overwritten (WHERE <table>.tenant_id = excluded.tenant_id).',
    '-- Provenance columns (sources_json, created_at) are written on first insert only.',
    '-- Run d1-preflight.sql first; every query there must return zero rows. Human approval gate: activation.',
    '-- Contains no events, metrics, conversions, users or personal information.',
  ];
  for (const t of def.tenants) {
    const c = t.campaign; const tid = t.tenant_id; const terr = t.school.territory_url;
    L.push('', `-- Tenant ${t.tenant_key}`);
    L.push(`INSERT INTO tenants (tenant_id, display_name, timezone, pilot_status, pilot_price_cents, created_at) VALUES (${[tid, t.display_name, t.timezone, 'pilot_fixture', 0, `${def.prepared_on}T00:00:00.000Z`].map(q).join(', ')})\n  ON CONFLICT (tenant_id) DO UPDATE SET display_name = excluded.display_name, timezone = excluded.timezone;`);
    L.push(`INSERT INTO schools (school_id, tenant_id, display_name, official_url, sources_json) VALUES (${[t.school.school_id, tid, t.school.display_name, terr, JSON.stringify(canonical([{ source: 'sponsor_definition', definition_key: def.definition_key, url: terr }]))].map(q).join(', ')})\n  ON CONFLICT (school_id) DO UPDATE SET display_name = excluded.display_name, official_url = excluded.official_url WHERE schools.tenant_id = excluded.tenant_id;`);
    for (const l of t.locations) {
      const verified = l.facts.map((f) => f.observed_on).sort().at(-1);
      const status = ready ? 'eligible_fixture' : 'needs_owner_confirmation';
      const reason = ready ? `Owner-approved for the live WWK commercial pilot beginning ${c.starts_on}.` : 'Awaiting recorded sponsor terms and source verification.';
      L.push(`INSERT INTO locations (location_id, tenant_id, school_id, display_name, address_display, official_url, status, status_reason, verified_on, sources_json) VALUES (${[l.location_id, tid, t.school.school_id, l.display_name, l.address_display, l.official_url, status, reason, verified, JSON.stringify(canonical(l.facts))].map(q).join(', ')})\n  ON CONFLICT (location_id) DO UPDATE SET display_name = excluded.display_name, address_display = excluded.address_display, official_url = excluded.official_url, status = excluded.status, status_reason = excluded.status_reason, verified_on = excluded.verified_on WHERE locations.tenant_id = excluded.tenant_id;`);
    }
    L.push(`INSERT INTO campaigns (campaign_id, tenant_id, school_id, kind, display_name, disclosure_label, price_cents, starts_on, ends_on) VALUES (${[c.campaign_id, tid, t.school.school_id, c.kind, c.display_name, c.disclosure_label, c.price_cents, c.starts_on, c.ends_on].map(q).join(', ')})\n  ON CONFLICT (campaign_id) DO UPDATE SET display_name = excluded.display_name, disclosure_label = excluded.disclosure_label, starts_on = excluded.starts_on, ends_on = excluded.ends_on WHERE campaigns.tenant_id = excluded.tenant_id;`);
    const locs = new Map(t.locations.map((l) => [l.location_key, l]));
    for (const d of t.destinations) {
      const l = d.location_key ? locs.get(d.location_key) : null;
      const url = l ? l.official_url : terr;
      const name = l ? `${l.display_name} (official location page)` : `${t.school.display_name} (official site)`;
      L.push(`INSERT INTO destinations (destination_id, tenant_id, location_id, display_name, url, host) VALUES (${[d.destination_id, tid, l ? l.location_id : null, name, url, new URL(url).hostname].map(q).join(', ')})\n  ON CONFLICT (destination_id) DO UPDATE SET location_id = excluded.location_id, display_name = excluded.display_name, url = excluded.url, host = excluded.host WHERE destinations.tenant_id = excluded.tenant_id;`);
    }
    for (const p of t.placements) {
      const featured = p.variant === 'featured_location' ? locs.get(p.location_keys[0]).location_id : null;
      L.push(`INSERT INTO placements (placement_id, tenant_id, campaign_id, kind, display_name, featured_location_id, link_rel, inventory_status) VALUES (${[p.placement_id, tid, c.campaign_id, 'sponsored_card', `Sponsored card: ${p.page_path}`, featured, LINK_REL, 'fixture_candidate'].map(q).join(', ')})\n  ON CONFLICT (placement_id) DO UPDATE SET campaign_id = excluded.campaign_id, display_name = excluded.display_name, featured_location_id = excluded.featured_location_id, link_rel = excluded.link_rel WHERE placements.tenant_id = excluded.tenant_id;`);
      L.push(`INSERT INTO placement_pages (placement_id, tenant_id, page_path, canonical_url, source_file) VALUES (${[p.placement_id, tid, p.page_path, `${SITE_ORIGIN}${p.page_path}`, sourceFileFor(p.page_path).file].map(q).join(', ')})\n  ON CONFLICT (placement_id, page_path) DO UPDATE SET canonical_url = excluded.canonical_url, source_file = excluded.source_file WHERE placement_pages.tenant_id = excluded.tenant_id;`);
      for (const d of placementDestinations(t, p)) L.push(`INSERT INTO placement_destinations (placement_id, destination_id, tenant_id) VALUES (${[p.placement_id, d.destination_id, tid].map(q).join(', ')}) ON CONFLICT (placement_id, destination_id) DO NOTHING;`);
    }
  }
  const detail = JSON.stringify({ definition_key: def.definition_key, definition_sha256: defSha, tenants: def.tenants.map((t) => t.tenant_id) });
  L.push('', '-- Audit entry, written once per definition version.',
    `INSERT INTO audit_log (at, actor, action, tenant_id, detail_json) SELECT ${q(`${def.prepared_on}T00:00:00.000Z`)}, ${q(ACTOR)}, 'sponsor.definition.apply', NULL, ${q(detail)}\n  WHERE NOT EXISTS (SELECT 1 FROM audit_log WHERE action = 'sponsor.definition.apply' AND detail_json = ${q(detail)});`, '');
  return L.join('\n');
}

function preflightSql(def) {
  const owned = []; const pids = []; const pages = []; const pairs = [];
  for (const t of def.tenants) {
    const tid = t.tenant_id;
    owned.push(['schools', 'school_id', t.school.school_id, tid], ['campaigns', 'campaign_id', t.campaign.campaign_id, tid]);
    for (const l of t.locations) owned.push(['locations', 'location_id', l.location_id, tid]);
    for (const d of t.destinations) owned.push(['destinations', 'destination_id', d.destination_id, tid]);
    for (const p of t.placements) {
      owned.push(['placements', 'placement_id', p.placement_id, tid]); pids.push(p.placement_id); pages.push(p.page_path);
      for (const d of placementDestinations(t, p)) pairs.push(`${p.placement_id}|${d.destination_id}`);
    }
  }
  const list = (xs) => xs.map(q).join(', ');
  return [
    `-- WWK sponsor activation PREFLIGHT (read-only). GENERATED by ${GENERATOR}.`,
    '-- Every query must return ZERO rows before d1-upsert.sql is applied.',
    '', '-- 1. IDs already owned by a different tenant.',
    `${owned.map(([tb, col, id, tid]) => `SELECT '${tb}' AS tbl, ${col} AS id, tenant_id FROM ${tb} WHERE ${col} = ${q(id)} AND tenant_id <> ${q(tid)}`).join('\nUNION ALL\n')};`,
    '', '-- 2. Pages that already carry a different sponsored card.',
    `SELECT pp.page_path, pp.placement_id, pp.tenant_id FROM placement_pages pp JOIN placements p ON p.placement_id = pp.placement_id WHERE p.kind = 'sponsored_card' AND pp.page_path IN (${list(pages)}) AND pp.placement_id NOT IN (${list(pids)});`,
    '', '-- 3. Destination links on these placements that the definition does not list (review; the upsert never deletes).',
    `SELECT placement_id, destination_id FROM placement_destinations WHERE placement_id IN (${list(pids)}) AND (placement_id || '|' || destination_id) NOT IN (${list(pairs)});`,
    '', '-- 4. Schema version must be 2 (operator_roles migration applied).',
    "SELECT key, value FROM schema_meta WHERE key = 'schema_version' AND value <> '2';",
    '', '-- 5. Destination hosts must already be allowed by the collector (changing this list is a separate, human-approved global change).',
    ...def.destination_hosts.map((h) => `SELECT ${q(h)} AS missing_host WHERE NOT EXISTS (SELECT 1 FROM schema_meta WHERE key = 'allowed_destination_hosts' AND value LIKE ${q(`%"${h}"%`)});`),
    `SELECT ${q(def.site.host)} AS missing_site_host WHERE NOT EXISTS (SELECT 1 FROM schema_meta WHERE key = 'allowed_site_hosts' AND value LIKE ${q(`%"${def.site.host}"%`)});`,
    '',
  ].join('\n');
}

function portalSql(def) {
  const L = [`-- WWK sponsor portal memberships. GENERATED by ${GENERATOR}. Human approval gate: portal_access.`,
    '-- Users are created WITHOUT an auth_subject, so nobody can sign in as them until the',
    '-- out-of-repo provisioning step binds the opaque HMAC subject. No email is ever stored.'];
  const tids = new Map(def.tenants.map((t) => [t.tenant_key, t.tenant_id]));
  for (const u of def.portal.users) {
    const uid = stableId('usr', `invite:${def.definition_key}:${u.invite_ref}`);
    L.push(`INSERT INTO users (user_id, display_label, auth_subject, is_demo) VALUES (${q(uid)}, ${q(u.display_label)}, NULL, 0)\n  ON CONFLICT (user_id) DO UPDATE SET display_label = excluded.display_label;`);
    for (const m of u.memberships) L.push(`INSERT INTO tenant_memberships (tenant_id, user_id, role) VALUES (${[tids.get(m.tenant_key), uid, m.role].map(q).join(', ')})\n  ON CONFLICT (tenant_id, user_id) DO UPDATE SET role = excluded.role;`);
  }
  return `${L.join('\n')}\n`;
}

