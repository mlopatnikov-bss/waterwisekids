// Minimal auto-escaping HTML templating. Every interpolated value is escaped unless
// it is a SafeHtml produced by this module.
class SafeHtml {
  constructor(s) { this.value = s; }
  toString() { return this.value; }
}

export function escapeHtml(v) {
  return String(v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

function render(v) {
  if (v === null || v === undefined || v === false) return '';
  if (v instanceof SafeHtml) return v.value;
  if (Array.isArray(v)) return v.map(render).join('');
  return escapeHtml(v);
}

export function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i += 1) out += render(values[i]) + strings[i + 1];
  return new SafeHtml(out);
}

/** Only for markup generated by this codebase (never for data). */
export function trusted(s) { return new SafeHtml(s); }

export const fmtInt = (n) => (n === null || n === undefined ? '—' : Math.round(n).toLocaleString('en-US'));
export const fmtPct = (num, den, digits = 1) => (den ? `${((num / den) * 100).toFixed(digits)}%` : '—');
